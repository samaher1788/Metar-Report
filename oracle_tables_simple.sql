-- الجدول الثالث: STATIONS
CREATE TABLE STATIONS (
    STATION_ID NUMBER,
    STATION_CODE VARCHAR2(10),
    STATION_NAME VARCHAR2(100),
    COUNTRY_CODE VARCHAR2(5),
    COUNTRY_NAME VARCHAR2(50),
    LATITUDE NUMBER(10,6),
    LONGITUDE NUMBER(10,6),
    ELEVATION NUMBER(10,2),
    ACTIVE_FLAG VARCHAR2(1),
    CREATED_AT TIMESTAMP
);

-- Primary Key
ALTER TABLE STATIONS ADD CONSTRAINT PK_STATIONS PRIMARY KEY (STATION_ID);

-- Unique
ALTER TABLE STATIONS ADD CONSTRAINT UK_STATION_CODE UNIQUE (STATION_CODE);

-- Not Null
ALTER TABLE STATIONS MODIFY STATION_CODE NOT NULL;

-- Sequence
CREATE SEQUENCE STATIONS_SEQ START WITH 1 INCREMENT BY 1;

-- Indexes
CREATE INDEX IDX_STATION_CODE ON STATIONS(STATION_CODE);
CREATE INDEX IDX_STATION_COUNTRY ON STATIONS(COUNTRY_CODE);

