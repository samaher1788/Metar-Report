-- الجدول الرابع: DAILY_STATISTICS
CREATE TABLE DAILY_STATISTICS (
    STAT_ID NUMBER,
    REPORT_DATE DATE,
    COUNTRY_CODE VARCHAR2(5),
    TOTAL_REPORTS NUMBER,
    BLDU_COUNT NUMBER,
    BLSA_COUNT NUMBER,
    DU_COUNT NUMBER,
    SA_COUNT NUMBER,
    DS_COUNT NUMBER,
    SS_COUNT NUMBER,
    PO_COUNT NUMBER,
    MIN_VISIBILITY NUMBER(10,2),
    MAX_WIND_SPEED NUMBER(5,2),
    CREATED_AT TIMESTAMP
);

-- Primary Key
ALTER TABLE DAILY_STATISTICS ADD CONSTRAINT PK_DAILY_STATISTICS PRIMARY KEY (STAT_ID);

-- Unique
ALTER TABLE DAILY_STATISTICS ADD CONSTRAINT UK_DAILY_STAT UNIQUE (REPORT_DATE, COUNTRY_CODE);

-- Not Null
ALTER TABLE DAILY_STATISTICS MODIFY REPORT_DATE NOT NULL;
ALTER TABLE DAILY_STATISTICS MODIFY COUNTRY_CODE NOT NULL;

-- Sequence
CREATE SEQUENCE DAILY_STATISTICS_SEQ START WITH 1 INCREMENT BY 1;

-- Indexes
