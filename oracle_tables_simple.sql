-- الجدول الثاني: DUST_PHENOMENA
CREATE TABLE DUST_PHENOMENA (
    PHENOMENON_ID NUMBER,
    REPORT_ID NUMBER,
    PHENOMENON_TYPE VARCHAR2(10),
    SEVERITY VARCHAR2(20),
    CREATED_AT TIMESTAMP
);

-- Primary Key
ALTER TABLE DUST_PHENOMENA ADD CONSTRAINT PK_DUST_PHENOMENA PRIMARY KEY (PHENOMENON_ID);

-- Foreign Key
ALTER TABLE DUST_PHENOMENA ADD CONSTRAINT FK_DUST_REPORT 
    FOREIGN KEY (REPORT_ID) REFERENCES METAR_REPORTS(REPORT_ID) ON DELETE CASCADE;

-- Not Null
ALTER TABLE DUST_PHENOMENA MODIFY REPORT_ID NOT NULL;
ALTER TABLE DUST_PHENOMENA MODIFY PHENOMENON_TYPE NOT NULL;

-- Sequence
CREATE SEQUENCE DUST_PHENOMENA_SEQ START WITH 1 INCREMENT BY 1;

-- Indexes
CREATE INDEX IDX_DUST_TYPE ON DUST_PHENOMENA(PHENOMENON_TYPE);
CREATE INDEX IDX_DUST_REPORT ON DUST_PHENOMENA(REPORT_ID);

